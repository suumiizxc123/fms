const pricePerLitre: Record<FuelType, number> = {
  "AI-92": 2390,
  "AI-95": 2780,
  Diesel: 3290,
  LPG: 1980,
};

const now = new Date();

const hours = Array.from({ length: 24 }, (_, index) => `${index.toString().padStart(2, "0")}:00`);
const weekdays = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"];
const weekWindows = ["W-7", "W-6", "W-5", "W-4", "W-3", "W-2", "W-1", "This"];

const makeHourly = (base: number): SalesPoint[] =>
  hours.map((label, index) => {
    const wave = 0.76 + Math.sin(index / 3.1) * 0.17;
    const litres = Math.round(base * wave + index * 16);
    return { label, litres, revenue: litres * 2550 };
  });

const makeDaily = (base: number): SalesPoint[] =>
  weekdays.map((label, index) => {
    const litres = Math.round(base + index * 180 + (index % 2 === 0 ? 120 : -80));
    return { label, litres, revenue: litres * 2590 };
  });

const makeWeekly = (base: number): SalesPoint[] =>
  weekWindows.map((label, index) => {
    const litres = Math.round(base + index * 720 + (index % 3) * 260);
    return { label, litres, revenue: litres * 2570 };
  });

const makeLossTrend = (base: number): TrendPoint[] =>
  weekWindows.map((label, index) => ({
    label,
    value: Number((base + index * 0.06 + (index % 2 === 0 ? 0.08 : -0.03)).toFixed(2)),
  }));

const makeRefillHistory = (fuelType: FuelType, source: string): RefillRecord[] =>
  [0, 5, 11, 18, 26].map((offset, index) => {
    const date = new Date(now);
    date.setDate(now.getDate() - offset);
    return {
      date: date.toISOString(),
      litres: 18000 + index * 2400,
      fuelType,
      source,
    };
  });

const makeVehicleEvents = (fuelType: FuelType): VehicleEvent[] =>
  Array.from({ length: 6 }, (_, index) => {
    const timestamp = new Date(now.getTime() - index * 18 * 60 * 1000).toISOString();
    const litres = 24 + index * 5;
    const direction: VehicleEvent["direction"] =
      index === 0 ? "fueling" : index % 2 === 0 ? "entering" : "leaving";
    const dispensedLitres = direction === "fueling" ? litres * 0.58 : direction === "leaving" ? litres : 0;
    return {
      id: `${fuelType}-${index}`,
      vehicleType: ["Sedan", "SUV", "Truck", "Bus"][index % 4] as VehicleEvent["vehicleType"],
      fuelType,
      litres,
      dispensedLitres,
      amountMnt: litres * pricePerLitre[fuelType],
      timestamp,
      bay: (index % 3) + 1,
      direction,
      progress: direction === "fueling" ? 0.58 : direction === "leaving" ? 0.42 : 0.18,
      active: index < 4,
    };
  });

